import * as fontkit from "fontkit";
import { writeFileSync } from "fs";

const FONT_PATH = "./public/ArialBI-Regular.ttf"; // Arial Bold Italic
const OUT_PATH = "./src/lib/char-widths.ts";

// ── Character sets ───────────────────────────────────────────

const range = (from: number, to: number): string[] =>
  Array.from({ length: to - from + 1 }, (_, i) =>
    String.fromCodePoint(from + i),
  );

const GROUPS: { name: string; chars: string[] }[] = [
  // Ukrainian alphabet (33 letters)
  {
    name: "Ukrainian uppercase",
    chars: [..."АБВГҐДЕЄЖЗИІЇЙКЛМНОПРСТУФХЦЧШЩЬЮЯ"],
  },
  {
    name: "Ukrainian lowercase",
    chars: [..."абвгґдеєжзиіїйклмнопрстуфхцчшщьюя"],
  },

  // Russian letters that Ukrainian does not have
  { name: "Russian-only uppercase", chars: [..."ЁЪЫЭ"] },
  { name: "Russian-only lowercase", chars: [..."ёъыэ"] },

  // English
  { name: "English uppercase", chars: range(0x41, 0x5a) },
  { name: "English lowercase", chars: range(0x61, 0x7a) },

  // Digits, spaces, punctuation
  { name: "digits", chars: range(0x30, 0x39) },
  { name: "space", chars: [" ", "\u00A0"] },
  {
    name: "ASCII punctuation",
    chars: [
      ...range(0x21, 0x2f),
      ...range(0x3a, 0x40),
      ...range(0x5b, 0x60),
      ...range(0x7b, 0x7e),
    ],
  },
  {
    name: "special symbols",
    chars: [
      "«",
      "»",
      "“",
      "”",
      "„",
      "‘",
      "’",
      "‚",
      "–",
      "—",
      "…",
      "•",
      "№",
      "©",
      "®",
      "™",
      "°",
      "±",
      "×",
      "÷",
      "§",
      "¶",
      "·",
      "€",
      "£",
      "¥",
      "¢",
    ],
  },
];

// ── Load font (handles .ttc collections too) ─────────────────

const opened = fontkit.openSync(FONT_PATH);
const font: fontkit.Font =
  "fonts" in opened ? (opened as any).fonts[0] : (opened as fontkit.Font);
const upm = font.unitsPerEm;

console.log(
  `Font: ${font.fullName} | postscript: ${font.postscriptName} | upm: ${upm}`,
);
// if (!/bold/i.test(font.fullName) || !/italic|oblique/i.test(font.fullName)) {
//   console.warn("⚠ This does not look like Arial Bold Italic. Check FONT_PATH.");
// }

// ── Build table ──────────────────────────────────────────────

const seen = new Set<string>();
const missing: string[] = [];
const lines: string[] = [];

for (const group of GROUPS) {
  lines.push(`  // ${group.name}`);
  for (const ch of group.chars) {
    if (seen.has(ch)) continue; // guard against duplicate keys
    seen.add(ch);

    const glyph = font.glyphForCodePoint(ch.codePointAt(0)!);
    if (!glyph || glyph.id === 0) {
      missing.push(ch);
      continue;
    }
    const w = Math.round((glyph.advanceWidth / upm) * 1000);
    lines.push(`  ${JSON.stringify(ch)}: ${w},`);
  }
  lines.push("");
}

const output = `// Generated by scripts/gen-widths.ts from ${font.fullName}. Do not edit by hand.
// Units per 1000 em.

export const DEFAULT_CHAR_WIDTH_1000 = 600;

export const CHAR_WIDTHS_1000: Record<string, number> = {
${lines.join("\n")}};
`;

writeFileSync(OUT_PATH, output);

console.log(`Wrote ${OUT_PATH} (${seen.size - missing.length} glyphs)`);
if (missing.length) {
  console.warn(
    `Missing glyphs (fallback width will be used): ${missing.join(" ")}`,
  );
}

// ── Sanity check: Latin should match known Arial Bold values ─

const expected: Record<string, number> = {
  A: 722,
  a: 556,
  W: 944,
  m: 889,
  i: 278,
};
for (const [ch, exp] of Object.entries(expected)) {
  const g = font.glyphForCodePoint(ch.codePointAt(0)!);
  const got = Math.round((g.advanceWidth / upm) * 1000);
  if (got !== exp)
    console.warn(`⚠ "${ch}" is ${got}, expected ${exp}. Wrong font file?`);
}
